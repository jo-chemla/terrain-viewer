'use client';

import { ApiReferenceReact } from '@scalar/api-reference-react';
import '@scalar/api-reference-react/style.css';
import { useEffect, useState } from 'react';

// The docs site's own theme: the `dark` class Fumadocs puts on <html>,
// watched so the reference follows the site's toggle without a reload.
function useSiteDark() {
  const [dark, setDark] = useState(false);
  useEffect(() => {
    const root = document.documentElement;
    const read = () => setDark(root.classList.contains('dark'));
    read();
    const observer = new MutationObserver(read);
    observer.observe(root, { attributes: true, attributeFilter: ['class'] });
    return () => observer.disconnect();
  }, []);
  return dark;
}

// Scalar's reference UI over public/openapi.json (generated by
// scripts/build-url-params.mjs): one GET / operation whose query parameters
// are every state and instruction parameter of the viewer, so its "try it"
// form doubles as a URL builder with the right control for each type.
// Its light or dark look follows the docs site (its own toggle is hidden).
export function ScalarReference() {
  const dark = useSiteDark();
  return (
    <div className="not-prose -mx-4 my-4">
      <ApiReferenceReact
        // Scalar reads the dark mode setting once, at mount: remount on a switch.
        key={dark ? 'dark' : 'light'}
        configuration={{
          url: '/docs/openapi.json',
          hideModels: true,
          hideDarkModeToggle: true,
          hideClientButton: true,
          showSidebar: false,
          layout: 'classic',
          theme: 'none',
          darkMode: dark,
          forceDarkModeState: dark ? 'dark' : 'light',
          // One operation: open it straight away rather than behind a fold.
          defaultOpenAllTags: true,
          expandAllResponses: true,
        }}
      />
    </div>
  );
}
